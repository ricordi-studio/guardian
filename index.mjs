#!/usr/bin/env node
/**
 * WHY.md の索引を作る(2026-08-29 依頼主の指示)。
 *
 * ★依頼主の言葉が、そのまま分類の軸である:
 *
 *   「情報と作法と器をちゃんと分けて、美しい構造化を進めたらいいだけ、その1点で全てが解決する。
 *    WHYに溜まっていくのは、それがちゃんと出来ていないことによる結果が積みあがってるだけ。
 *    **欲しいのは、美しい構造化の実現につながる発見・発明の芽です。**
 *    そういうのは大変価値のある事故例です。
 *    しょうもない事故報告は、扱いが低くていいです。」
 *
 * ★だから索引は「全部を平等に並べる」ものではない。**重みを付ける**:
 *
 *   ◎ 構造の芽 … 情報/作法/器 の分け方が一段進んだもの。**これだけが本当に欲しいもの**
 *   ○ 型       … 同じ形が繰り返された記録。まとめて読めばよい
 *   ・ 個別     … その場を直した記録。索引では1行で足りる
 *
 * ★なぜ索引が要るか: WHY は増え続け、install.md は「まず WHY を読め」と言っている。
 *   200件、500件になれば、また LLM のコンテキストの問題が戻ってくる。
 *   **全部保存する。だが毎回全部は読ませない。**
 *
 * ★分類は機械が下ごしらえし、**人とAIが直す**。語の一致で決まる分類は当たらないことがあるので、
 *   索引には「これは機械が推した分類です」と書いてある。直したものは `WHY_WEIGHT` に残り、次から尊重される。
 *
 * 使い方:
 *   node guardian/index.mjs            … WHY_INDEX.md を作る
 *   node guardian/index.mjs --check    … 作らずに、索引が古くなっていないかだけ見る
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* ★【この道具が知っている口】── 宣言ではなく、ここが実装そのものである
 *   (2026-08-31、第2の議題。配布先(現場A)の実測が発端)。
 *
 * ★実際に起きたこと: 案内されている口を「ソースにその文字列が在るか」で照合したら、
 *   3通りの数え方で3通りの答えが出た。とくに `neighbors --list` は**文字列としては在るが、
 *   argv を見ていない**(既定動作だった)── **書いてある ≠ 口として在る**。
 *   これは 9.46 で `PROTOCOL.json` に置き換えたばかりの「綴りで能力を測る」罠と同じ形である。
 * ★だから【この配列が唯一の正】にする: ここが未知の口を拒み、ここが `--口一覧` を答える。
 *   selfcheck の B11 が、SPEC.md の表と**この出力**を突き合わせる(44条の双子)。
 * ★穴として書く: これが証明するのは「その口を受け付ける」までで、
 *   **その口が仕事をする**ことではない。そこは各口の検査の仕事。 */
const 知っている口 = ['--口一覧', '--check'];
const 値を取る口 = {};
const 残りを全部取る口 = [];
/* ★順番: **未知の口の走査が先、`--口一覧` は後**(2026-08-31、配布先の実測)。
 *   検査は `--口一覧 --zzz` の形で叩く ── 門が生きていれば **出口1**、
 *   門が壊れていれば `--zzz` が無視されて **口一覧が出て出口0**。
 *   ★逆順だと、門が壊れていても口一覧が先に出て**緑に見える**。
 *   ★そして「壊れている側で、その道具が本当に走り出す」ことも避けられる ──
 *     素の `--zzz` で叩くと、門が壊れた `verdict` は**本物の合否を回し始める**(検査が検査を呼ぶ)。 */
{
  const 渡された = process.argv.slice(2);
  const 知らない = [];
  for (let i = 0; i < 渡された.length; i++) {
    const v = 渡された[i];
    if (!v.startsWith('--')) continue;          /* 口の値は飛ばす */
    if (残りを全部取る口.includes(v)) break;     /* ここから先は全部その口の値 */
    if (!知っている口.includes(v)) { 知らない.push(v); continue; }
    i += (値を取る口[v] || 0);
  }
  if (知らない.length) {
    console.error('✗ この道具は、その口を知りません: ' + 知らない.join(', '));
    console.error('  知っている口: ' + 知っている口.join(' / '));
    console.error('  ★黙って無視すると、打ったつもりと違う動きをしたまま報告することになります');
    process.exit(1);
  }
}
if (process.argv.includes('--口一覧')) {
  process.stdout.write(知っている口.join(String.fromCharCode(10)) + String.fromCharCode(10));
  process.exit(0);
}

const HERE = path.dirname(fileURLToPath(import.meta.url));
const 見るだけ = process.argv.includes('--check');

const WHY = (() => {
  try { return fs.readFileSync(path.join(HERE, 'WHY.md'), 'utf8'); }
  catch (_) { console.error('WHY.md が読めません'); process.exit(1); }
})();

/* 人が直した重みは尊重する(機械の推しより人の判断が上) */
const 人の重み = (() => {
  const m = {};
  try {
    for (const 行 of fs.readFileSync(path.join(HERE, 'WHY_WEIGHT'), 'utf8').split(/\r?\n/)) {
      const x = 行.match(/^([◎○・])\s+(.+)$/);
      if (x) m[x[2].trim()] = x[1];
    }
  } catch (_) {}
  return m;
})();

/* ── 節に切る ── */
const 節 = WHY.split(/^(?=## \[)/m).filter((s) => s.startsWith('## ['));

/* ── 機械の下ごしらえ ──
 * ★「構造の芽」は、**分け方そのものが動いた**ときに出る言葉で拾う。
 *   これは当たらないことがある ── だから索引に「機械が推した」と明記し、人が直せるようにする。 */
const 構造の語 = ['情報と作法', '作法の棚', '器が持たない', '一般化', 'メタ化', '正本を1つ',
  '1箇所に', '構造で止める', '不変のID', '分け方', '棚に', '宣言が持つ', '写経',
  '同じことを2か所', '名前が中身より狭い', '役割を分け'];
const 型の語 = ['同じ形', '3度目', '2回連続', '4度目', '二度', '同じ過ち', '繰り返'];

const 重み = (s) => {
  const 題 = s.split(/\r?\n/)[0].replace(/^##\s*/, '').trim();
  if (人の重み[題]) return { w: 人の重み[題], 題, 人: true };
  const 本文 = s.slice(0, 2500);
  if (構造の語.some((w) => 本文.includes(w))) return { w: '◎', 題, 人: false };
  if (型の語.some((w) => 本文.includes(w))) return { w: '○', 題, 人: false };
  return { w: '・', 題, 人: false };
};

const 分 = 節.map((s) => {
  const r = 重み(s);
  /* 1行要約 = 「★規律:」の行があればそこ、無ければ本文の最初の1行 */
  const 行 = s.split(/\r?\n/).slice(1).map((x) => x.trim()).filter(Boolean);
  const 規律 = 行.find((x) => x.startsWith('★規律:')) || '';
  const 要約 = (規律 || 行.find((x) => !x.startsWith('#')) || '').replace(/^★規律:\s*/, '').slice(0, 90);
  return { ...r, 要約 };
});

const 数 = (w) => 分.filter((x) => x.w === w).length;
const 出 = [
  '# WHY の索引(重み付き)',
  '',
  '**この索引は `node guardian/index.mjs` が作ります。手で直さないでください** ──',
  '直したい重みは `WHY_WEIGHT` に書くと、次回から尊重されます。',
  '',
  '## 重みの意味(依頼主の言葉が軸)',
  '',
  '> 情報と作法と器をちゃんと分けて、美しい構造化を進めたらいいだけ、その1点で全てが解決する。',
  '> WHYに溜まっていくのは、それがちゃんと出来ていないことによる結果が積みあがってるだけ。',
  '> **欲しいのは、美しい構造化の実現につながる発見・発明の芽。**',
  '',
  '| 重み | 意味 | 読み方 |',
  '|---|---|---|',
  '| ◎ | **構造の芽** ── 情報/作法/器の分け方が一段進んだもの | **これだけは全部読む価値がある** |',
  '| ○ | 型 ── 同じ形が繰り返された記録 | まとめて読めばよい |',
  '| ・ | 個別 ── その場を直した記録 | 索引の1行で足りる |',
  '',
  '★**分類は機械の下ごしらえ**(語の一致)。当たらないことがあるので、',
  '  読んで違うと思ったら `WHY_WEIGHT` に書いてください ── 人の判断が機械の推しより上です。',
  '',
  '★**この索引は「読まなくていい」を作るためのものではありません。**',
  '  全部の事故は WHY.md に残ります。索引は「**いま関係するものだけ渡す**」ための地図です。',
  '',
  '---',
  '',
];
for (const w of ['◎', '○', '・']) {
  出.push('## ' + w + ' ' + { '◎': '構造の芽', '○': '型(繰り返し)', '・': '個別' }[w]
    + '(' + 数(w) + '件)', '');
  for (const x of 分.filter((y) => y.w === w))
    出.push('- ' + (x.人 ? '**[人]** ' : '') + x.題 + (x.要約 ? '  ' + String.fromCharCode(10) + '  ' + x.要約 : ''));
  出.push('');
}

const 先 = path.join(HERE, 'WHY_INDEX.md');
const 新 = 出.join('\n');
if (見るだけ) {
  let 旧 = '';
  try { 旧 = fs.readFileSync(先, 'utf8'); } catch (_) {}
  const 同じ = 旧.replace(/\r\n/g, '\n') === 新;
  console.log(同じ ? '索引は最新です' : '★索引が古くなっています(node guardian/index.mjs で作り直せます)');
  process.exit(同じ ? 0 : 1);
}
fs.writeFileSync(先, 新);
console.log('WHY_INDEX.md を作りました: ◎' + 数('◎') + '件 / ○' + 数('○') + '件 / ・' + 数('・') + '件');
console.log('★◎(構造の芽)だけが本当に欲しいもの。他は「まだ構造化できていない」ことの記録です。');
